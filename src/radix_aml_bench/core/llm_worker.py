import asyncio
import logging
import time

from openai import AsyncOpenAI
from pydantic import BaseModel, Field, ValidationError

from radix_aml_bench.domains import ResponseRegistry, SampleRegistry
from radix_aml_bench.prompts import SystemPromptRegistry, UserPromptRegistry
from radix_aml_bench.settings import MAX_TOKENS, MODEL_NAME

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)


class ResponseSchema(BaseModel):
    """The schema for the response from the LLM."""

    ttft_ms: float = Field(description="Time to first token in milliseconds")
    e2e_ms: float = Field(description="End-to-end latency in milliseconds")
    output_tokens: int = Field(description="Number of output tokens generated by the LLM")
    valid_json: bool = Field(description="Whether the response was valid JSON matching the schema")


async def run_llm_request(
    domain: str,
    client: AsyncOpenAI,
    semaphore: asyncio.Semaphore,
    request_id: int,
) -> ResponseSchema:
    """Run a single LLM request and return the response metrics."""

    # get domain's objects
    samples = SampleRegistry.get(domain)
    shared_system_prompt = SystemPromptRegistry.get(domain)
    user_prompt_template = UserPromptRegistry.get(domain)
    domain_schema = ResponseRegistry.get(domain)

    sample_text = samples[request_id % len(samples)]
    user_prompt = user_prompt_template.format(request_id, sample_text)

    async with semaphore:
        logger.info(f"Running LLM request {request_id}")
        start_time = time.perf_counter()
        ttft = None
        chunks: list[str] = []
        output_tokens: int | None = None

        response = await client.chat.completions.create(
            model=MODEL_NAME,
            messages=[
                {"role": "system", "content": shared_system_prompt},
                {"role": "user", "content": user_prompt},
            ],
            temperature=0.0,
            max_tokens=MAX_TOKENS,
            response_format={
                "type": "json_schema",
                "json_schema": {
                    "name": "ResponseSchema",
                    "strict": True,
                    "schema": domain_schema.model_json_schema(),
                },
            },
            stream=True,
            stream_options={"include_usage": True},
            timeout=900
        )

        logger.info("completed API call")
        async for chunk in response:
            delta = chunk.choices[0].delta.content if chunk.choices else None
            if delta:
                if ttft is None:
                    ttft = time.perf_counter() - start_time
                chunks.append(delta)
            if getattr(chunk, "usage", None) is not None:
                output_tokens = chunk.usage.completion_tokens

        end_time = time.perf_counter() - start_time
        ttft_ms = (ttft if ttft is not None else end_time) * 1000
        e2e_ms = end_time * 1000
        if output_tokens is None:
            output_tokens = len(chunks)

        # validate the JSON response against the schema
        valid_json = False
        full_output = "".join(chunks)
        try:
            domain_schema.model_validate_json(full_output)
            valid_json = True
        except ValidationError:
            valid_json = False

        return ResponseSchema(
            ttft_ms=ttft_ms,
            e2e_ms=e2e_ms,
            output_tokens=output_tokens,
            valid_json=valid_json,
        )