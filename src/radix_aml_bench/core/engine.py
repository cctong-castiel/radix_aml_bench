import asyncio
import logging
import statistics
import time

from openai import AsyncOpenAI
from pydantic import BaseModel, Field

from radix_aml_bench.core.llm_worker import run_llm_request
from radix_aml_bench.settings import CONCURRENCY, TOTAL_REQUESTS, WARMUP_REQUESTS

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)


class BenchmarkResult(BaseModel):
    """The result of a benchmark."""

    engine: str = Field(description="The engine that was benchmarked")
    requests: int = Field(description="The total number of requests")
    concurrency: int = Field(description="The number of concurrent requests")
    wall_time: float = Field(description="The total wall time of the benchmark")
    throughput: float = Field(description="The throughput of the benchmark (requests per second)")
    output_tokens_per_second: float = Field(description="The total number of output tokens generated by the engine per second")
    ttft_p50_ms: float = Field(description="The 50th percentile time to first token (TTFT) in milliseconds")
    ttft_p95_ms: float = Field(description="The 95th percentile time to first token (TTFT) in milliseconds")
    e2e_p50_ms: float = Field(description="The 50th percentile end-to-end latency (E2E) in milliseconds")
    schema_valid_pct: float = Field(description="The percentage of responses that were valid JSON matching the schema")


class Engine:
    """An interface for an engine that can be benchmarked."""

    def __init__(self, name: str, url: str, api_key: str):
        self.engine_name = name
        self.url = url
        self.api_key = api_key

    async def run_benchmark(
        self,
        domain_name: str = "aml"
    ) -> "BenchmarkResult":
        """Run a benchmark on the engine."""
        logger.info(f"Running benchmark on engine: {self.engine_name}")

        semaphore = asyncio.Semaphore(CONCURRENCY)

        async with AsyncOpenAI(base_url=self.url, api_key=self.api_key) as client:
            # Warm up all backend replicas' Radix tree / KV cache and CUDA graphs
            warmup_tasks = [
                run_llm_request(
                    domain=domain_name,
                    client=client,
                    semaphore=semaphore,
                    request_id=i,
                )
                for i in range(WARMUP_REQUESTS)
            ]
            await asyncio.gather(*warmup_tasks)

            start_wall_time = time.perf_counter()
            tasks = [
                run_llm_request(
                    domain=domain_name,
                    client=client,
                    semaphore=semaphore,
                    request_id=i,
                )
                for i in range(1, TOTAL_REQUESTS + 1)
            ]
            results = await asyncio.gather(*tasks)
            end_wall_time = time.perf_counter() - start_wall_time

        ttfts = sorted(r.ttft_ms for r in results)
        e2e_ms = sorted(r.e2e_ms for r in results)
        output_tokens = sum(r.output_tokens for r in results)
        valid_rate = sum(1 for r in results if r.valid_json) / len(results) * 100
        p95_idx = max(0, int(0.95 * len(ttfts)) - 1)

        return BenchmarkResult(
            engine=self.engine_name,
            requests=TOTAL_REQUESTS,
            concurrency=CONCURRENCY,
            wall_time=round(end_wall_time, 2),
            throughput=round(len(results) / end_wall_time, 2),
            output_tokens_per_second=round(output_tokens / end_wall_time, 2),
            ttft_p50_ms=round(statistics.median(ttfts), 2),
            ttft_p95_ms=round(ttfts[p95_idx], 2),
            e2e_p50_ms=round(statistics.median(e2e_ms), 2),
            schema_valid_pct=round(valid_rate, 2),
        )
